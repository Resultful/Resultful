namespace Matchmark.Generator
{
    /// <summary>An operation as the spec defines it, for checking hand-written endpoints against.</summary>
    internal sealed class SpecOperation
    {
        public SpecOperation(string id, string method, string path, IReadOnlyList<int> statuses, IReadOnlyList<SpecParameter> parameters, string? bodyType,
            IOpenApiSchema? bodySchema, IReadOnlyDictionary<int, IOpenApiSchema?> responseSchemas)
        {
            BodySchema = bodySchema;
            ResponseSchemas = responseSchemas;
            Id = id;
            Method = method;
            Path = path;
            Statuses = statuses;
            Parameters = parameters;
            BodyType = bodyType;
        }

        public string Id { get; }

        public string Method { get; }

        public string Path { get; }

        public IReadOnlyList<int> Statuses { get; }

        /// <summary>The path, query and header parameters.</summary>
        public IReadOnlyList<SpecParameter> Parameters { get; }

        /// <summary>The request body's C# type, or null when the operation has no body.</summary>
        public string? BodyType { get; }

        public IOpenApiSchema? BodySchema { get; }

        /// <summary>Each documented status's body schema; null for a response without a body.</summary>
        public IReadOnlyDictionary<int, IOpenApiSchema?> ResponseSchemas { get; }
    }

    /// <summary>A path, query or header parameter: where it comes from, its name, its C# type and whether it's required.</summary>
    internal sealed class SpecParameter
    {
        public SpecParameter(string source, string name, string type, bool required, IReadOnlyList<(string Keyword, string Value)> constraints)
        {
            Constraints = constraints;
            Source = source;
            Name = name;
            Type = type;
            Required = required;
        }

        /// <summary>Route, Query or Header.</summary>
        public string Source { get; }

        public string Name { get; }

        public string Type { get; }

        public bool Required { get; }

        /// <summary>The schema's validation keywords (minLength, maximum, pattern...), normalised as Constraints.Of reads them.</summary>
        public IReadOnlyList<(string Keyword, string Value)> Constraints { get; }
    }

    internal sealed partial class Emitter
    {
        public IReadOnlyList<SpecOperation> Operations()
        {
            CollectSchemas();
            return CollectOperations()
                .Select(o => new SpecOperation(
                    o.Id,
                    o.Method,
                    o.Path,
                    o.Successes.Concat(o.Errors).Select(r => r.Status).OrderBy(s => s).ToList(),
                    o.Parameters.Select(p => new SpecParameter(
                        p.Attribute.Substring(4), p.Name, p.Type.TrimEnd('?'), !p.Type.EndsWith("?", StringComparison.Ordinal),
                        p.Schema is null ? Array.Empty<(string, string)>() : Constraints.Of(p.Schema))).ToList(),
                    o.Body?.Type,
                    o.Body?.Schema,
                    o.Successes.Concat(o.Errors).ToDictionary(r => r.Status, r => r.Schema)))
                .ToList();
        }
    }
