        private string EmitController(string tag, List<Operation> operations)
        {
            var w = new CodeWriter(_namespace);
            w.Usings("System.Collections.Generic", "System.Threading", "System.Threading.Tasks", "Microsoft.AspNetCore.Http", "Microsoft.AspNetCore.Mvc",
                "Microsoft.AspNetCore.Mvc.Infrastructure", "Microsoft.AspNetCore.Mvc.ModelBinding", "Microsoft.Extensions.DependencyInjection", "Resultful");
            var name = $"{Naming.Pascal(tag)}Controller";
            w.Line("/// <summary>");
            w.Line($"/// The <c>{tag}</c> operations as an ASP.NET Core controller. Each action calls <see cref=\"{HandlerInterface(tag)}\"/> and turns");
            w.Line("/// its outcome into the documented response; the attributes describe exactly the responses the spec documents.");
            w.Line("/// </summary>");
            w.Line("[ApiController]");
            w.Line($"[Tags({Naming.Literal(tag)})]");
            w.Open($"public sealed class {name}({HandlerInterface(tag)} handlers) : ControllerBase");
            foreach (var operation in operations)
            {
                var verb = operation.Method switch
                {
                    "GET" => "HttpGet",
                    "POST" => "HttpPost",
                    "PUT" => "HttpPut",
                    "DELETE" => "HttpDelete",
                    "PATCH" => "HttpPatch",
                    _ => "HttpGet",
                };
                w.Line($"/// <summary><c>{operation.Method} {operation.Path}</c></summary>");
                w.Line($"[{verb}({Naming.Literal(operation.Path)}, Name = {Naming.Literal(operation.Id)})]");
                if (operation.Body is not null)
                {
                    w.Line($"[Consumes({Naming.Literal(operation.Body.MediaType)})]");
                }

                foreach (var response in operation.Successes.Concat(operation.Errors).Where(r => !r.CarriesStatus))
                {
                    w.Line(response.BodyType is null || response.IsRedirect
                        ? $"[ProducesResponseType({response.Status.Invariant()})]"
                        : $"[ProducesResponseType<{response.BodyType}>({response.Status.Invariant()}, {Naming.Literal(response.MediaType!)})]");
                }

                if (operation.Body is not null && !operation.ValidationDocumented)
                {
                    w.Line("[ProducesResponseType<HttpValidationProblemDetails>(400, \"application/problem+json\")]");
                }

                var args = operation.Parameters.Where(p => !p.Deep)
                    .Select(p => p.Enum ? $"[{p.Attribute}(Name = {Naming.Literal(p.Name)})] string? __text_{p.Identifier.TrimStart('@')}" : $"[{p.Attribute}(Name = {Naming.Literal(p.Name)})] {p.Type} {p.Identifier}")
                    .ToList();
                var call = operation.Parameters.Select(p => p.Identifier).ToList();
                if (operation.Body is { Form: false, Text: false })
                {
                    args.Add($"[FromBody] {operation.Body.Type} body");
                }

                if (operation.Body is not null)
                {
                    call.Add("body");
                }

                w.Open($"public async Task<IActionResult> {operation.Name}({string.Join(", ", args.Append("CancellationToken cancellationToken"))})");
                EmitEnumReads(w, operation, "return ValidationProblem(modelStateDictionary: Invalid({0}));");
                foreach (var deep in operation.Parameters.Where(p => p.Deep))
                {
                    EmitDeepRead(w, deep, "Request.Query", "cancellationToken",
                        $"{{{{ var (key, message) = {ValidationClass}.BindingError(({{0}}).Path ?? \"$\", ({{0}}).Message); return ValidationProblem(modelStateDictionary: Invalid(new Dictionary<string, string[]> {{{{ [key] = [message] }}}})); }}}}");
                }

                if (operation.Body is { Text: true } text)
                {
                    // Text, read as it is.
                    w.Open($"if (Request.ContentType?.StartsWith({Naming.Literal(text.MediaType)}, System.StringComparison.OrdinalIgnoreCase) != true)");
                    w.Line("return StatusCode(StatusCodes.Status415UnsupportedMediaType);");
                    w.Close();
                    w.Line();
                    w.Line("var body = await new System.IO.StreamReader(Request.Body).ReadToEndAsync(cancellationToken);");
                    w.Open($"if ({ValidationClass}.CheckText(body, {(text.Schema.MinLength ?? (operation.RequiredBody ? 1 : 0)).Invariant()}, {(text.Schema.MaxLength?.Invariant() ?? "null")}, {(text.Schema.Pattern is { } textPattern ? Naming.Literal(textPattern) : "null")}) is {{ }} textErrors)");
                    w.Line("return ValidationProblem(modelStateDictionary: Invalid(textErrors));");
                    w.Close();
                    w.Line();
                }

                if (operation.Body is { Form: true } form)
                {
                    // Read here rather than bound by MVC, so that nested values in brackets work, as the generated endpoints read it.
                    w.Open("if (!Request.HasFormContentType)");
                    w.Line("return StatusCode(StatusCodes.Status415UnsupportedMediaType);");
                    w.Close();
                    w.Line();
                    w.Line($"{form.Type} body;");
                    w.Open("try");
                    w.Line($"body = {ValidationClass}.ReadForm<{form.Type}>(global::System.Linq.Enumerable.SelectMany(await Request.ReadFormAsync(cancellationToken), f => global::System.Linq.Enumerable.Select(f.Value, v => new KeyValuePair<string, string>(f.Key, v ?? string.Empty))));");
                    w.Close();
                    w.Open("catch (System.Text.Json.JsonException e)");
                    w.Line($"var (key, message) = {ValidationClass}.BindingError(e.Path ?? \"$\", e.Message);");
                    w.Line("return ValidationProblem(modelStateDictionary: Invalid(new Dictionary<string, string[]> { [key] = [message] }));");
                    w.Close();
                    w.Line();
                }

                if (operation.Body is { Validated: true })
                {
                    w.Open($"if ({ValidationClass}.Validate(body) is {{ }} errors)");
                    w.Line("return ValidationProblem(modelStateDictionary: Invalid(errors));");
                    w.Close();
                    w.Line();
                }

                var invoke = $"await handlers.{operation.Name}({string.Join(", ", call.Append("cancellationToken"))})";
                var hasValue = operation.SuccessIsUnion || operation.Successes[0].BodyType is not null;
                var apply = operation.ResponseHeaders.Count > 0 ? "foreach (var header in headers.Values) Response.Headers[header.Key] = header.Value;" : null;
                if (apply is not null)
                {
                    w.Line($"using var headers = {_apiName}Headers.Begin();");
                }

                if (operation.Errors.Count == 0)
                {
                    if (!hasValue)
                    {
                        w.Line($"{invoke};");
                        if (apply is not null)
                        {
                            w.Line(apply);
                        }

                        w.Line($"return {Action(operation.Successes[0], "null")};");
                    }
                    else
                    {
                        w.Line($"var value = {invoke};");
                        if (apply is not null)
                        {
                            w.Line(apply);
                        }

                        w.Line($"return {ActionSuccess(operation, "value")};");
                    }
                }
                else
                {
                    w.Line($"var result = {invoke};");
                    if (apply is not null)
                    {
                        w.Line(apply);
                    }

                    w.Line("return result.Match<IActionResult>(");
                    w.Line($"    success => {ActionSuccess(operation, "success")},");
                    w.Line($"    error => error.Match<IActionResult>({string.Join(", ", operation.Errors.Select(e => $"@case => {Action(e, "@case.Body")}"))}));");
                }

                w.Close();
                w.Line();
            }

            w.Line("/// <summary>");
            w.Line("/// A problem as application/problem+json, with the status the spec gives it, completed (type, trace id) the way MVC");
            w.Line("/// completes its own problems, so it reads the same as the generated endpoints' problems.");
            w.Line("/// </summary>");
            w.Open("private ObjectResult ProblemResponse(ProblemDetails problem, int status)");
            w.Line("var completed = HttpContext.RequestServices.GetRequiredService<ProblemDetailsFactory>()");
            w.Line("    .CreateProblemDetails(HttpContext, status, problem.Title, problem.Type, problem.Detail, problem.Instance);");
            w.Line("foreach (var (key, value) in problem.Extensions)");
            w.Line("{");
            w.Line("    completed.Extensions[key] = value;");
            w.Line("}");
            w.Line();
            w.Line("return new ObjectResult(completed) { StatusCode = status, ContentTypes = { \"application/problem+json\" } };");
            w.Close();
            w.Line();
            w.Line("/// <summary>Validation errors keyed by JSON path, for <see cref=\"ControllerBase.ValidationProblem()\"/>.</summary>");
            w.Open("private static ModelStateDictionary Invalid(IDictionary<string, string[]> errors)");
            w.Line("var state = new ModelStateDictionary();");
            w.Line("foreach (var (key, messages) in errors)");
            w.Line("{");
            w.Line("    foreach (var message in messages)");
            w.Line("    {");
            w.Line("        state.AddModelError(key, message);");
            w.Line("    }");
            w.Line("}");
            w.Line();
            w.Line("return state;");
            w.Close();
            w.Close();
            return w.ToString();
        }

        private string ActionSuccess(Operation operation, string value)
            => operation.SuccessIsUnion
                ? $"{value}.Match<IActionResult>({string.Join(", ", operation.Successes.Select(s => $"@case => {Action(s, "@case.Body")}"))})"
                : Action(operation.Successes[0], value);

        /// <summary>The ControllerBase result for a documented response, given its body.</summary>
        private string Action(Response response, string body) => response switch
        {
            { IsStream: true } => $"new {_apiName}JsonLines<{response.ItemType}>({body}, {Naming.Literal(response.MediaType!)})",
            { IsRedirect: true, Status: 301 } => $"RedirectPermanent({body})",
            { IsRedirect: true, Status: 307 } => $"RedirectPreserveMethod({body})",
            { IsRedirect: true, Status: 308 } => $"RedirectPermanentPreserveMethod({body})",
            { IsRedirect: true } => $"Redirect({body})",
            { CarriesStatus: true, BodyType: null } => $"StatusCode({Response.StatusOf(body)})",
            { CarriesStatus: true, IsProblem: true } => $"ProblemResponse({body}, {Response.StatusOf(body)})",
            { CarriesStatus: true } => $"StatusCode({Response.StatusOf(body)}, {body})",
            { IsValidation: true } => $"ValidationProblem(detail: {body}.Detail, title: {body}.Title, modelStateDictionary: Invalid({body}.Errors))",
            { IsProblem: true } => $"ProblemResponse({body}, {response.Status.Invariant()})",
            { BodyType: null, Status: 204 } => "NoContent()",
            { BodyType: null } => $"StatusCode({response.Status.Invariant()})",
            { Status: 200 } => $"Ok({body})",
            { Status: 201 } => $"Created((string?)null, {body})",
            { Status: 202 } => $"Accepted({body})",
            _ => $"StatusCode({response.Status.Invariant()}, {body})",
        };

        /// <summary>The JSON and MVC conventions the spec implies, for controllers.</summary>
        private string EmitConventions(bool streams = false)
        {
            var w = new CodeWriter(_namespace);
            w.Usings("System", "System.Linq", "System.Text.Json.Serialization", "System.Text.RegularExpressions", "Microsoft.AspNetCore.Mvc",
                "Microsoft.AspNetCore.Mvc.Filters", "Microsoft.AspNetCore.Mvc.Formatters", "Microsoft.AspNetCore.Mvc.Infrastructure",
                "Microsoft.AspNetCore.Mvc.ModelBinding", "Microsoft.Extensions.DependencyInjection");
            w.Open($"public static class {_apiName}Conventions");
            w.Line("/// <summary>");
            w.Line("/// JSON as the spec reads it (numbers are numbers; a oneOf discriminator may come anywhere), for both MVC and the");
            w.Line("/// OpenAPI document. Requests that can't be bound get the spec's validation problem, worded as the generated");
            w.Line($"/// endpoints word it ({ValidationClass}.BindingError); the spec's constraints are checked by the generated validator, not");
            w.Line("/// by MVC's DataAnnotations.");
            w.Line("/// </summary>");
            w.Open($"public static IServiceCollection Add{_apiName}Conventions(this IServiceCollection services)");
            w.Line("services.ConfigureHttpJsonOptions(options =>");
            w.Line("{");
            w.Line("    options.SerializerOptions.NumberHandling = JsonNumberHandling.Strict;");
            w.Line("    options.SerializerOptions.AllowOutOfOrderMetadataProperties = true;");
            w.Line($"    options.SerializerOptions.TypeInfoResolver = global::System.Text.Json.Serialization.Metadata.JsonTypeInfoResolver.WithAddedModifier(options.SerializerOptions.TypeInfoResolver ?? new global::System.Text.Json.Serialization.Metadata.DefaultJsonTypeInfoResolver(), {ValidationClass}.RefuseNulls);");
            w.Line("});");
            w.Line("services.Configure<JsonOptions>(options =>");
            w.Line("{");
            w.Line("    options.JsonSerializerOptions.NumberHandling = JsonNumberHandling.Strict;");
            w.Line("    options.JsonSerializerOptions.AllowOutOfOrderMetadataProperties = true;");
            w.Line($"    options.JsonSerializerOptions.TypeInfoResolver = global::System.Text.Json.Serialization.Metadata.JsonTypeInfoResolver.WithAddedModifier(options.JsonSerializerOptions.TypeInfoResolver ?? new global::System.Text.Json.Serialization.Metadata.DefaultJsonTypeInfoResolver(), {ValidationClass}.RefuseNulls);");
            w.Line("});");
            w.Line("services.Configure<ApiBehaviorOptions>(options => options.InvalidModelStateResponseFactory = context =>");
            w.Line("{");
            w.Line("    // Only binding failures reach here (no validators run): answer the first, preferring the JSON path it happened at.");
            w.Line("    var (key, entry) = context.ModelState.Where(e => e.Value?.Errors.Count > 0).OrderBy(e => e.Key.StartsWith('$') ? 0 : 1).First();");
            w.Line("    var failure = entry!.Errors[0];");
            w.Line($"    var (name, message) = {ValidationClass}.BindingError(key, failure.ErrorMessage.Length > 0 ? failure.ErrorMessage : failure.Exception?.Message ?? string.Empty);");
            w.Line("    return Problem(context.HttpContext, name, message);");
            w.Line("});");
            w.Line();
            w.Line("services.Configure<MvcOptions>(options =>");
            w.Line("{");
            w.Line("    // The generated validator checks the spec's constraints; MVC's DataAnnotations would check them again, worded differently.");
            w.Line("    options.ModelValidatorProviders.Clear();");
            w.Line();
            w.Line("    // A body missing its oneOf discriminator fails with NotSupportedException, which MVC's JSON input doesn't catch.");
            w.Line("    options.Filters.Add(new MissingDiscriminator());");
            w.Line();
            w.Line("    // MVC's JSON input also accepts application/*+json and text/json; the spec documents application/json only.");
            w.Line("    foreach (var json in options.InputFormatters.OfType<SystemTextJsonInputFormatter>())");
            w.Line("    {");
            w.Line("        json.SupportedMediaTypes.Remove(\"application/*+json\");");
            w.Line("        json.SupportedMediaTypes.Remove(\"text/json\");");
            w.Line("    }");
            w.Line("});");
            w.Line("return services;");
            w.Close();
            w.Line();
            w.Block(ConventionsProblems.Replace("{Validation}", ValidationClass));
            w.Close();
            if (streams)
            {
                w.Line();
                w.Line("/// <summary>A sequential body (OpenAPI 3.2's itemSchema): JSON Lines, or server-sent events, each item written as it comes.</summary>");
                w.Open($"public sealed class {_apiName}JsonLines<T>(global::System.Collections.Generic.IAsyncEnumerable<T> items, string mediaType) : IActionResult");
                w.Open("public async global::System.Threading.Tasks.Task ExecuteResultAsync(ActionContext context)");
                w.Line("var response = context.HttpContext.Response;");
                w.Line("response.ContentType = mediaType;");
                w.Open("await foreach (var item in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.WithCancellation(items, context.HttpContext.RequestAborted))");
                w.Open("if (mediaType == \"text/event-stream\")");
                w.Line("// A server-sent event: its data the item, as JSON, or the text of a string.");
                w.Line("var data = item is string text ? text : System.Text.Json.JsonSerializer.Serialize(item, System.Text.Json.JsonSerializerOptions.Web);");
                w.Line("await response.Body.WriteAsync(System.Text.Encoding.UTF8.GetBytes(\"data: \" + data + \"\\n\\n\"));");
                w.Line("await response.Body.FlushAsync();");
                w.Line("continue;");
                w.Close();
                w.Line();
                w.Line("await System.Text.Json.JsonSerializer.SerializeAsync(response.Body, item, System.Text.Json.JsonSerializerOptions.Web);");
                w.Line("await response.Body.WriteAsync(new byte[] { 10 });");
                w.Close();
                w.Close();
                w.Close();
            }

            return w.ToString();
        }

        private const string ConventionsProblems = @"/// <summary>The spec's validation problem for one value, as MVC writes problems.</summary>
private static BadRequestObjectResult Problem(Microsoft.AspNetCore.Http.HttpContext context, string name, string message)
{
    var errors = new ModelStateDictionary();
    errors.AddModelError(name, message);
    return new BadRequestObjectResult(context.RequestServices.GetRequiredService<ProblemDetailsFactory>().CreateValidationProblemDetails(context, errors));
}

/// <summary>A body missing its oneOf discriminator: a validation problem, not a 500.</summary>
private sealed class MissingDiscriminator : IExceptionFilter
{
    public void OnException(ExceptionContext context)
    {
        if (context.Exception is NotSupportedException { Source: ""System.Text.Json"" } e && e.Message.Contains(""type discriminator"", StringComparison.Ordinal))
        {
            var (name, message) = {Validation}.BindingError(Regex.Match(e.Message, @""Path: (\$\S*)"").Groups[1].Value, e.Message);
            context.Result = Problem(context.HttpContext, name, message);
            context.ExceptionHandled = true;
        }
    }
}";

        private string EmitProgram(List<Operation> operations, string contractNamespace, bool controllers)
        {
            var lines = new List<string>
            {
                "using Microsoft.AspNetCore.Builder;",
                "using Microsoft.Extensions.DependencyInjection;",
                $"using {contractNamespace};",
                $"using {_namespace};",
                string.Empty,
                "var builder = WebApplication.CreateBuilder(args);",
            };
            lines.Add(controllers ? "builder.Services.AddControllers();" : $"builder.Services.Add{_apiName}();");
            if (controllers)
            {
                lines.Add($"builder.Services.Add{_apiName}Conventions();");
            }

            lines.Add("builder.Services.AddProblemDetails();");
            lines.Add($"builder.Services.AddOpenApi(options => options.Add{_apiName}Schemas());");
            foreach (var tag in operations.Select(o => o.Tag).Distinct())
            {
                lines.Add($"builder.Services.AddScoped<{HandlerInterface(tag)}, {Naming.Pascal(tag)}Handlers>();");
            }

            lines.Add(string.Empty);
            lines.Add("var app = builder.Build();");
            lines.Add("app.MapOpenApi();");
            lines.Add(controllers ? "app.MapControllers();" : $"app.Map{_apiName}();");
            lines.Add("app.Run();");
            return string.Join("\n", lines) + "\n";
        }
    }

    /// <summary>Writes the server side of a spec as owned ASP.NET source. Used by the Matchmark.Cli tool.</summary>
    public static class Scaffolder
    {
        /// <summary>
        /// The files to write, by relative path. <paramref name="contractNamespace"/> is where the generated contract lives;
        /// <paramref name="projectNamespace"/> is the namespace of the scaffolded code.
        /// </summary>
        public static IReadOnlyDictionary<string, string> Scaffold(
            string specText, string specName, string contractNamespace, string projectNamespace, string apiName, bool controllers,
            out IReadOnlyList<string> warnings)
            => Scaffold(specText, specName, contractNamespace, projectNamespace, apiName, controllers, Array.Empty<(string, string)>(), out warnings);

        /// <summary>The same, with overlays applied to the spec first.</summary>
        public static IReadOnlyDictionary<string, string> Scaffold(
            string specText, string specName, string contractNamespace, string projectNamespace, string apiName, bool controllers,
            IEnumerable<(string Text, string Path)> overlays, out IReadOnlyList<string> warnings)
        {
            var document = SpecReader.Read(specText, specName, out var problems, overlays)
                ?? throw new InvalidOperationException($"{specName} could not be read: {string.Join("; ", problems)}");
            var emitter = new Emitter(document, projectNamespace, apiName, Microsoft.CodeAnalysis.Location.None, describesItself: true);
            var files = emitter.Scaffold(contractNamespace, specName, controllers);
            warnings = problems.Select(p => $"the reader objected: {p}")
                .Concat(emitter.Diagnostics.Select(d => d.GetMessage(CultureInfo.InvariantCulture)))
                .ToList();
            return files;
        }
    }
