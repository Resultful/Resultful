using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text.Json.Nodes;
using Microsoft.OpenApi;
using Microsoft.OpenApi.Reader;

namespace Resultful.OpenApi.Generator
{
    /// <summary>
    /// Scaffolding: the server side written out once as ordinary ASP.NET source the team owns. Controllers (or Minimal API
    /// endpoints), a reference implementation of each handler interface that answers with the spec's examples, the
    /// JSON and OpenAPI conventions the spec implies, and Program.cs. The contract (types, unions, interfaces) stays generated.
    /// </summary>
    internal sealed partial class Emitter
    {
        public Dictionary<string, string> Scaffold(string contractNamespace, string spec, bool controllers)
        {
            CollectSchemas();
            var operations = CollectOperations();
            var files = new Dictionary<string, string>();
            var header = Header(spec);

            foreach (var group in operations.GroupBy(o => o.Tag))
            {
                files[$"{Naming.Pascal(group.Key)}Handlers.cs"] = Owned(EmitReferenceHandlers(group.Key, group.ToList()), header, contractNamespace);
                if (controllers)
                {
                    files[$"Controllers/{Naming.Pascal(group.Key)}Controller.cs"] = Owned(EmitController(group.Key, group.ToList()), header, contractNamespace);
                }
            }

            if (controllers)
            {
                files[$"{_apiName}Conventions.cs"] = Owned(EmitConventions(), header, contractNamespace);
            }
            else
            {
                files[$"{_apiName}Endpoints.cs"] = Owned(EmitEndpoints(operations), header, contractNamespace);
            }

            files[$"{_apiName}OpenApi.cs"] = Owned(EmitOpenApi(contractNamespace), header, contractNamespace);
            files["Program.cs"] = header + EmitProgram(operations, contractNamespace, controllers);
            return files;
        }

        private static string Header(string spec)
            => $"// Scaffolded from {spec} by Resultful.OpenApi.Scaffold. This file is yours: edit it freely, it is never\n"
               + "// regenerated. The contract it implements (the types, unions and handler interfaces) stays generated.\n";

        /// <summary>Generated source as owned source: the scaffold header, and the contract's namespace in scope.</summary>
        private static string Owned(string generated, string header, string contractNamespace)
        {
            var text = generated.Replace("// <auto-generated/>\n", header);
            var index = text.IndexOf("\nnamespace ", StringComparison.Ordinal);
            return text.Substring(0, index) + $"using {contractNamespace};\n" + text.Substring(index);
        }

        // ---------------------------------------------------------------- reference implementation

        private string EmitReferenceHandlers(string tag, List<Operation> operations)
        {
            var w = new CodeWriter(_namespace);
            w.Usings("System", "System.Collections.Generic", "System.Globalization", "System.Threading", "System.Threading.Tasks",
                "Microsoft.AspNetCore.Http", "Microsoft.AspNetCore.Mvc", "Resultful");
            var name = $"{Naming.Pascal(tag)}Handlers";
            w.Line("/// <summary>");
            w.Line($"/// The reference implementation of <see cref=\"{HandlerInterface(tag)}\"/>: every operation answers with its first documented");
            w.Line("/// success, built from the spec's example (or a sample that passes the schema). Replace each body with the real behaviour;");
            w.Line("/// the contract suite and outcome coverage show what is still a reference answer.");
            w.Line("/// </summary>");
            w.Open($"public sealed class {name} : {HandlerInterface(tag)}");
            var first = true;
            foreach (var operation in operations)
            {
                if (!first)
                {
                    w.Line();
                }

                first = false;
                var args = operation.Parameters.Select(p => $"{p.Type} {p.Identifier}").ToList();
                if (operation.Body is not null)
                {
                    args.Add($"{operation.Body.Type} body");
                }

                var response = operation.Successes[0];
                var outcomes = string.Join(", ", operation.Successes.Concat(operation.Errors).Select(r => $"{r.Status.Invariant()} {r.CaseName}"));
                w.Line($"/// <summary><c>{operation.Method} {operation.Path}</c>. Documented outcomes: {outcomes}.</summary>");
                w.Open($"public {operation.HandlerReturnType} {operation.Name}({string.Join(", ", args.Append("CancellationToken cancellationToken"))})");
                w.Line($"// TODO: replace this reference answer (the spec's {response.Status.Invariant()} {response.CaseName}) with the real behaviour.");
                string? value = null;
                if (response.BodyType is not null && response.SampleJson is { } sample)
                {
                    w.Line($"{response.BodyType} answer = {CSharp(JsonNode.Parse(sample), response.Schema, response.BodyType)};");
                    value = "answer";
                }

                var outcome = Outcome(operation, response, value);
                w.Line(operation.HandlerResultType is { } result
                    ? $"return Task.FromResult<{result}>({outcome});"
                    : "return Task.CompletedTask;");
                w.Close();
            }

            w.Close();
            return w.ToString();
        }

        /// <summary>A JSON value as a C# expression of the generated types: object initialisers, enum members, literals.</summary>
        private string CSharp(JsonNode? node, IOpenApiSchema? schema, string type)
        {
            if (node is null)
            {
                return "null!";
            }

            if (schema is not null && RefId(schema) is { } id)
            {
                if (id == "ProblemDetails" || id == ValidationSchema)
                {
                    var props = (node as JsonObject ?? new JsonObject())
                        .Where(p => p.Key is "title" or "detail" or "type" or "instance" or "status" && p.Value is not null)
                        .Select(p => $"{Naming.Pascal(p.Key)} = {Scalar(p.Value!)}");
                    return $"new {type} {{ {string.Join(", ", props)} }}";
                }

                if (_schemas.TryGetValue(id, out var target))
                {
                    if (IsEnum(target))
                    {
                        return $"{Naming.Pascal(id)}.{Naming.Pascal(node.GetValue<string>())}";
                    }

                    if (target.OneOf is { Count: > 0 } && target.Discriminator?.PropertyName is { } discriminator)
                    {
                        var value = node[discriminator]?.GetValue<string>();
                        var member = _unionMembers.FirstOrDefault(m => m.Value.Base == id && m.Value.Value == value).Key;
                        return member is null ? Fallback(node, type) : CSharp(node, new OpenApiSchemaReference(member, _document), Naming.Pascal(member));
                    }

                    var parts = new List<string>();
                    _unionMembers.TryGetValue(id, out var union);
                    foreach (var property in target.Properties ?? new Dictionary<string, IOpenApiSchema>())
                    {
                        if (property.Key == union.Property || node is not JsonObject obj || !obj.TryGetPropertyValue(property.Key, out var value))
                        {
                            continue;
                        }

                        var propertyType = TypeOf(property.Value, id) ?? "object";
                        parts.Add($"{Naming.Pascal(property.Key)} = {(value is null ? "null" : CSharp(value, property.Value, propertyType))}");
                    }

                    return $"new {Naming.Pascal(id)} {{ {string.Join(", ", parts)} }}";
                }
            }

            if (schema is not null && Has(schema, JsonSchemaType.Array) && node is JsonArray array)
            {
                var item = schema.Items is { } items ? TypeOf(items, "item") ?? "object" : "object";
                return $"[{string.Join(", ", array.Select(e => CSharp(e, schema.Items, item)))}]";
            }

            return schema?.Format switch
            {
                "date-time" => $"DateTimeOffset.Parse({Naming.Literal(node.GetValue<string>())}, CultureInfo.InvariantCulture)",
                "date" => $"DateOnly.Parse({Naming.Literal(node.GetValue<string>())}, CultureInfo.InvariantCulture)",
                "uuid" => $"Guid.Parse({Naming.Literal(node.GetValue<string>())})",
                _ => node is JsonValue ? Scalar(node) : Fallback(node, type),
            };
        }

        private static string Scalar(JsonNode value) => value.GetValueKind() switch
        {
            System.Text.Json.JsonValueKind.String => Naming.Literal(value.GetValue<string>()),
            System.Text.Json.JsonValueKind.True => "true",
            System.Text.Json.JsonValueKind.False => "false",
            _ => value.ToJsonString(),
        };

        private static string Fallback(JsonNode node, string type)
            => $"System.Text.Json.JsonSerializer.Deserialize<{type}>({Naming.Literal(node.ToJsonString())}, System.Text.Json.JsonSerializerOptions.Web)!";

        // ---------------------------------------------------------------- controllers

        private string EmitController(string tag, List<Operation> operations)
        {
            var w = new CodeWriter(_namespace);
            w.Usings("System.Threading", "System.Threading.Tasks", "Microsoft.AspNetCore.Http", "Microsoft.AspNetCore.Mvc", "Resultful");
            var name = $"{Naming.Pascal(tag)}Controller";
            w.Line("/// <summary>");
            w.Line($"/// The <c>{tag}</c> operations as an ASP.NET Core controller. Each action calls <see cref=\"{HandlerInterface(tag)}\"/> and turns");
            w.Line("/// its outcome into the documented response; the attributes describe exactly the responses the spec documents.");
            w.Line("/// </summary>");
            w.Line("[ApiController]");
            w.Line($"[Tags({Naming.Literal(tag)})]");
            w.Open($"public sealed class {name}({HandlerInterface(tag)} handlers) : ControllerBase");
            foreach (var operation in operations)
            {
                var verb = operation.Method switch
                {
                    "GET" => "HttpGet",
                    "POST" => "HttpPost",
                    "PUT" => "HttpPut",
                    "DELETE" => "HttpDelete",
                    "PATCH" => "HttpPatch",
                    _ => "HttpGet",
                };
                w.Line($"/// <summary><c>{operation.Method} {operation.Path}</c></summary>");
                w.Line($"[{verb}({Naming.Literal(operation.Path)}, Name = {Naming.Literal(operation.Id)})]");
                if (operation.Body is not null)
                {
                    w.Line("[Consumes(\"application/json\")]");
                }

                foreach (var response in operation.Successes.Concat(operation.Errors))
                {
                    w.Line(response.BodyType is null
                        ? $"[ProducesResponseType({response.Status.Invariant()})]"
                        : $"[ProducesResponseType<{response.BodyType}>({response.Status.Invariant()}, {Naming.Literal(response.MediaType!)})]");
                }

                if (operation.Body is not null && !operation.ValidationDocumented)
                {
                    w.Line("[ProducesResponseType<HttpValidationProblemDetails>(400, \"application/problem+json\")]");
                }

                var args = operation.Parameters
                    .Select(p => $"[{p.Attribute}(Name = {Naming.Literal(p.Name)})] {p.Type} {p.Identifier}")
                    .ToList();
                var call = operation.Parameters.Select(p => p.Identifier).ToList();
                if (operation.Body is not null)
                {
                    args.Add($"[FromBody] {operation.Body.Type} body");
                    call.Add("body");
                }

                w.Open($"public async Task<IActionResult> {operation.Name}({string.Join(", ", args.Append("CancellationToken cancellationToken"))})");
                if (operation.Body is not null)
                {
                    w.Open($"if ({ValidationClass}.Validate(body) is {{ }} errors)");
                    w.Line("return ValidationProblem(new ValidationProblemDetails(errors));");
                    w.Close();
                    w.Line();
                }

                var invoke = $"await handlers.{operation.Name}({string.Join(", ", call.Append("cancellationToken"))})";
                var hasValue = operation.SuccessIsUnion || operation.Successes[0].BodyType is not null;
                if (operation.Errors.Count == 0)
                {
                    if (!hasValue)
                    {
                        w.Line($"{invoke};");
                        w.Line($"return {Action(operation.Successes[0], "null")};");
                    }
                    else
                    {
                        w.Line($"var value = {invoke};");
                        w.Line($"return {ActionSuccess(operation, "value")};");
                    }
                }
                else
                {
                    w.Line($"var result = {invoke};");
                    w.Line("return result.Match<IActionResult>(");
                    w.Line($"    success => {ActionSuccess(operation, "success")},");
                    w.Line($"    error => error.Match<IActionResult>({string.Join(", ", operation.Errors.Select(e => $"@case => {Action(e, "@case.Body")}"))}));");
                }

                w.Close();
                w.Line();
            }

            w.Line("/// <summary>A problem as application/problem+json, with the status the spec gives it.</summary>");
            w.Open("private static ObjectResult ProblemResponse(ProblemDetails problem, int status)");
            w.Line("problem.Status = status;");
            w.Line("return new ObjectResult(problem) { StatusCode = status, ContentTypes = { \"application/problem+json\" } };");
            w.Close();
            w.Close();
            return w.ToString();
        }

        private static string ActionSuccess(Operation operation, string value)
            => operation.SuccessIsUnion
                ? $"{value}.Match<IActionResult>({string.Join(", ", operation.Successes.Select(s => $"@case => {Action(s, "@case.Body")}"))})"
                : Action(operation.Successes[0], value);

        /// <summary>The ControllerBase result for a documented response, given its body.</summary>
        private static string Action(Response response, string body) => response switch
        {
            { IsValidation: true } => $"ValidationProblem(new ValidationProblemDetails({body}.Errors) {{ Title = {body}.Title, Detail = {body}.Detail }})",
            { IsProblem: true } => $"ProblemResponse({body}, {response.Status.Invariant()})",
            { BodyType: null, Status: 204 } => "NoContent()",
            { BodyType: null } => $"StatusCode({response.Status.Invariant()})",
            { Status: 200 } => $"Ok({body})",
            { Status: 201 } => $"Created((string?)null, {body})",
            { Status: 202 } => $"Accepted({body})",
            _ => $"StatusCode({response.Status.Invariant()}, {body})",
        };

        /// <summary>The JSON and MVC conventions the spec implies, for controllers.</summary>
        private string EmitConventions()
        {
            var w = new CodeWriter(_namespace);
            w.Usings("System.Linq", "System.Text.Json.Serialization", "Microsoft.AspNetCore.Mvc", "Microsoft.AspNetCore.Mvc.Formatters",
                "Microsoft.Extensions.DependencyInjection");
            w.Open($"public static class {_apiName}Conventions");
            w.Line("/// <summary>");
            w.Line("/// JSON as the spec reads it (numbers are numbers; a oneOf discriminator may come anywhere), for both MVC and the");
            w.Line("/// OpenAPI document; and request validation from the spec's constraints rather than MVC's automatic 400.");
            w.Line("/// </summary>");
            w.Open($"public static IServiceCollection Add{_apiName}Conventions(this IServiceCollection services)");
            w.Line("services.ConfigureHttpJsonOptions(options =>");
            w.Line("{");
            w.Line("    options.SerializerOptions.NumberHandling = JsonNumberHandling.Strict;");
            w.Line("    options.SerializerOptions.AllowOutOfOrderMetadataProperties = true;");
            w.Line("});");
            w.Line("services.Configure<JsonOptions>(options =>");
            w.Line("{");
            w.Line("    options.JsonSerializerOptions.NumberHandling = JsonNumberHandling.Strict;");
            w.Line("    options.JsonSerializerOptions.AllowOutOfOrderMetadataProperties = true;");
            w.Line("});");
            w.Line("services.Configure<ApiBehaviorOptions>(options => options.SuppressModelStateInvalidFilter = true);");
            w.Line();
            w.Line("// MVC's JSON input also accepts application/*+json and text/json; the spec documents application/json only.");
            w.Line("services.Configure<MvcOptions>(options =>");
            w.Line("{");
            w.Line("    foreach (var json in options.InputFormatters.OfType<SystemTextJsonInputFormatter>())");
            w.Line("    {");
            w.Line("        json.SupportedMediaTypes.Remove(\"application/*+json\");");
            w.Line("        json.SupportedMediaTypes.Remove(\"text/json\");");
            w.Line("    }");
            w.Line("});");
            w.Line("return services;");
            w.Close();
            w.Close();
            return w.ToString();
        }

        private string EmitProgram(List<Operation> operations, string contractNamespace, bool controllers)
        {
            var lines = new List<string>
            {
                "using Microsoft.AspNetCore.Builder;",
                "using Microsoft.Extensions.DependencyInjection;",
                $"using {contractNamespace};",
                $"using {_namespace};",
                string.Empty,
                "var builder = WebApplication.CreateBuilder(args);",
            };
            lines.Add(controllers ? "builder.Services.AddControllers();" : $"builder.Services.Add{_apiName}();");
            if (controllers)
            {
                lines.Add($"builder.Services.Add{_apiName}Conventions();");
            }

            lines.Add("builder.Services.AddProblemDetails();");
            lines.Add($"builder.Services.AddOpenApi(options => options.Add{_apiName}Schemas());");
            foreach (var tag in operations.Select(o => o.Tag).Distinct())
            {
                lines.Add($"builder.Services.AddScoped<{HandlerInterface(tag)}, {Naming.Pascal(tag)}Handlers>();");
            }

            lines.Add(string.Empty);
            lines.Add("var app = builder.Build();");
            lines.Add("app.MapOpenApi();");
            lines.Add(controllers ? "app.MapControllers();" : $"app.Map{_apiName}();");
            lines.Add("app.Run();");
            return string.Join("\n", lines) + "\n";
        }
    }

    /// <summary>Writes the server side of a spec as owned ASP.NET source. Used by the Resultful.OpenApi.Scaffold tool.</summary>
    public static class Scaffolder
    {
        /// <summary>
        /// The files to write, by relative path. <paramref name="contractNamespace"/> is where the generated contract lives;
        /// <paramref name="projectNamespace"/> is the namespace of the scaffolded code.
        /// </summary>
        public static IReadOnlyDictionary<string, string> Scaffold(
            string specText, string specName, string contractNamespace, string projectNamespace, string apiName, bool controllers,
            out IReadOnlyList<string> warnings)
        {
            var settings = new OpenApiReaderSettings();
            settings.AddYamlReader();
            var format = specName.EndsWith(".json", StringComparison.OrdinalIgnoreCase) ? "json" : "yaml";
            var read = OpenApiDocument.Parse(specText, format, settings);
            if (read.Document is null || read.Diagnostic?.Errors.Count > 0)
            {
                throw new InvalidOperationException("The spec could not be read: "
                    + string.Join("; ", read.Diagnostic?.Errors.Select(e => e.ToString()) ?? Enumerable.Empty<string>()));
            }

            var emitter = new Emitter(read.Document, projectNamespace, apiName, Microsoft.CodeAnalysis.Location.None, describesItself: true);
            var files = emitter.Scaffold(contractNamespace, specName, controllers);
            warnings = emitter.Diagnostics.Select(d => d.GetMessage(CultureInfo.InvariantCulture)).ToList();
            return files;
        }
    }
}

namespace Resultful.OpenApi.Generator
{
    /// <summary>An operation as the spec defines it, for checking hand-written endpoints against.</summary>
    internal sealed class SpecOperation
    {
        public SpecOperation(string id, string method, string path, IReadOnlyList<int> statuses, IReadOnlyList<SpecParameter> parameters, string? bodyType)
        {
            Id = id;
            Method = method;
            Path = path;
            Statuses = statuses;
            Parameters = parameters;
            BodyType = bodyType;
        }

        public string Id { get; }

        public string Method { get; }

        public string Path { get; }

        public IReadOnlyList<int> Statuses { get; }

        /// <summary>The path, query and header parameters.</summary>
        public IReadOnlyList<SpecParameter> Parameters { get; }

        /// <summary>The request body's C# type, or null when the operation has no body.</summary>
        public string? BodyType { get; }
    }

    /// <summary>A path, query or header parameter: where it comes from, its name, its C# type and whether it's required.</summary>
    internal sealed class SpecParameter
    {
        public SpecParameter(string source, string name, string type, bool required)
        {
            Source = source;
            Name = name;
            Type = type;
            Required = required;
        }

        /// <summary>Route, Query or Header.</summary>
        public string Source { get; }

        public string Name { get; }

        public string Type { get; }

        public bool Required { get; }
    }

    internal sealed partial class Emitter
    {
        public IReadOnlyList<SpecOperation> Operations()
        {
            CollectSchemas();
            return CollectOperations()
                .Select(o => new SpecOperation(
                    o.Id,
                    o.Method,
                    o.Path,
                    o.Successes.Concat(o.Errors).Select(r => r.Status).OrderBy(s => s).ToList(),
                    o.Parameters.Select(p => new SpecParameter(
                        p.Attribute.Substring(4), p.Name, p.Type.TrimEnd('?'), !p.Type.EndsWith("?", StringComparison.Ordinal))).ToList(),
                    o.Body?.Type))
                .ToList();
        }
    }
}
