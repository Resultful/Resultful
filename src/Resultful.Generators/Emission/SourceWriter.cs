using System.Text;
using Resultful.Generators.Models;

namespace Resultful.Generators.Emission;

internal sealed class SourceWriter
{
    private readonly StringBuilder _sb = new(1024);
    private int _indent;

    public void WriteLine() => _sb.Append('\n');

    public void WriteLine(string line)
    {
        for (var i = 0; i < _indent; i++)
        {
            _sb.Append("    ");
        }

        _sb.Append(line);
        _sb.Append('\n');
    }

    public void OpenBrace()
    {
        WriteLine("{");
        _indent++;
    }

    public void CloseBrace(string suffix = "")
    {
        _indent--;
        WriteLine("}" + suffix);
    }

    public void OpenNamespaceAndEnclosing(string? ns, EquatableArray<EnclosingTypeModel> enclosing, bool nullableAttributes = true)
    {
        WriteLine("// <auto-generated/>");
        // Without MaybeNullWhen and NotNullWhen (a netstandard2.0 consumer) the forwarders can't state their contract,
        // so the file keeps its annotations but reports no nullable warnings of its own.
        WriteLine(nullableAttributes ? "#nullable enable" : "#nullable enable annotations");
        // RF0002 (Resultful.Analyzers): generated members build zero values on purpose (decision 10).
        WriteLine("#pragma warning disable RF0002");
        WriteLine();
        if (!string.IsNullOrEmpty(ns))
        {
            WriteLine($"namespace {ns}");
            OpenBrace();
        }

        for (var i = 0; i < enclosing.Length; i++)
        {
            var e = enclosing[i];
            WriteLine($"{e.Accessibility} partial {e.Keyword} {e.Name}");
            OpenBrace();
        }
    }

    public void CloseNamespaceAndEnclosing(string? ns, EquatableArray<EnclosingTypeModel> enclosing)
    {
        for (var i = 0; i < enclosing.Length; i++)
        {
            CloseBrace();
        }

        if (!string.IsNullOrEmpty(ns))
        {
            CloseBrace();
        }
    }

    public override string ToString() => _sb.ToString();

    // `[global::System.Diagnostics.CodeAnalysis.Name(value)] ` when the consumer can name the attribute, else nothing.
    public static string FlowAttribute(bool available, string name, bool value) =>
        available ? $"[global::System.Diagnostics.CodeAnalysis.{name}({(value ? "true" : "false")})] " : "";
}
